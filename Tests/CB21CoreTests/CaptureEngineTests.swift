import Foundation
import Testing
@testable import CB21Core

final class FakePasteboard: PasteboardReading, @unchecked Sendable {
    private let lock = NSLock()
    private var _changeCount = 0
    private var current = PasteboardSnapshot(changeCount: 0, markers: [], representations: [])
    private(set) var written: [Clip] = []

    var changeCount: Int { lock.withLock { _changeCount } }

    func copy(_ text: String, markers: Set<String> = []) {
        lock.withLock {
            _changeCount += 1
            current = PasteboardSnapshot(
                changeCount: _changeCount,
                markers: markers,
                representations: [Representation(kind: .plainText, typeIdentifier: "public.utf8-plain-text", data: Data(text.utf8))]
            )
        }
    }

    func copyNothing() {
        lock.withLock {
            _changeCount += 1
            current = PasteboardSnapshot(changeCount: _changeCount, markers: [], representations: [])
        }
    }

    func snapshot() -> PasteboardSnapshot { lock.withLock { current } }

    func write(_ clip: Clip) -> Int {
        lock.withLock {
            _changeCount += 1
            written.append(clip)
            current = PasteboardSnapshot(changeCount: _changeCount, markers: [], representations: clip.representations)
            return _changeCount
        }
    }
}

private func makeEngine(_ pasteboard: FakePasteboard) throws -> (CaptureEngine, ClipStore) {
    let store = try ClipStore.inMemory()
    return (CaptureEngine(pasteboard: pasteboard, store: store), store)
}

@Test func pollWithoutAChangeDoesNothing() async throws {
    let (engine, _) = try makeEngine(FakePasteboard())
    #expect(try await engine.poll() == .unchanged)
}

@Test func newCopyIsCaptured() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copy("hello")
    #expect(try await engine.poll() == .captured(.stored))
    #expect(try await store.count() == 1)
}

@Test func contentAlreadyOnThePasteboardAtLaunchIsNotCaptured() async throws {
    let pb = FakePasteboard()
    pb.copy("secret from before launch")
    let (engine, store) = try makeEngine(pb)
    #expect(try await engine.poll() == .unchanged)
    #expect(try await store.count() == 0)
}

@Test func sameChangeIsNotCapturedTwice() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copy("x")
    _ = try await engine.poll()
    #expect(try await engine.poll() == .unchanged)
    #expect(try await store.count() == 1)
}

@Test func concealedCopiesAreSkippedAndLeaveNoTrace() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copy("hunter2", markers: [PasteboardMarker.concealed])
    #expect(try await engine.poll() == .skipped(.concealed))
    #expect(try await store.count() == 0)
}

@Test func transientCopiesAreSkipped() async throws {
    let pb = FakePasteboard()
    let (engine, _) = try makeEngine(pb)
    pb.copy("temp", markers: [PasteboardMarker.transient])
    #expect(try await engine.poll() == .skipped(.transient))
}

@Test func autoGeneratedCopiesAreStillCaptured() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copy("generated", markers: [PasteboardMarker.autoGenerated])
    #expect(try await engine.poll() == .captured(.stored))
    #expect(try await store.count() == 1)
}

@Test func skippedCopyIsNotCapturedOnALaterPoll() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copy("secret", markers: [PasteboardMarker.concealed])
    _ = try await engine.poll()
    #expect(try await engine.poll() == .unchanged)
    #expect(try await store.count() == 0)
}

@Test func emptyPasteboardChangeCapturesNothing() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copyNothing()
    #expect(try await engine.poll() == .empty)
    #expect(try await store.count() == 0)
}

@Test func recopyWritesThePasteboardAndIsNotCapturedAgain() async throws {
    let pb = FakePasteboard()
    let (engine, store) = try makeEngine(pb)
    pb.copy("A")
    _ = try await engine.poll()
    pb.copy("B")
    _ = try await engine.poll()
    let a = try await store.list().last!
    try await engine.recopy(id: a.id)
    #expect(pb.written.map(\.id) == [a.id])
    #expect(try await engine.poll() == .skipped(.ownWrite))
    let order = try await store.list().map(\.id)
    #expect(order.first == a.id)
    #expect(order.count == 2)
}
