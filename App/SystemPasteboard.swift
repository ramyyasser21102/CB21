import AppKit
import CB21Core

/// `NSPasteboard.general` as seen by `CaptureEngine`.
final class SystemPasteboard: PasteboardReading, @unchecked Sendable {
    private let pasteboard = NSPasteboard.general

    var changeCount: Int { pasteboard.changeCount }

    /// True when the user has set "Paste from Other Apps" to deny for cb21 (macOS 15.4 and later).
    var isAccessDenied: Bool {
        if #available(macOS 15.4, *) {
            return pasteboard.accessBehavior == .alwaysDeny
        }
        return false
    }

    func snapshot() -> PasteboardSnapshot {
        let types = pasteboard.pasteboardItems?.first?.types ?? []
        let markers = Set(types.map(\.rawValue)).intersection([
            PasteboardMarker.concealed, PasteboardMarker.transient, PasteboardMarker.autoGenerated,
        ])
        var representations: [Representation] = []
        if let item = pasteboard.pasteboardItems?.first {
            for type in item.types {
                guard let kind = Representation.Kind.classify(type.rawValue),
                      let data = item.data(forType: type), !data.isEmpty else { continue }
                representations.append(Representation(kind: kind, typeIdentifier: type.rawValue, data: data))
            }
        }
        return PasteboardSnapshot(changeCount: pasteboard.changeCount, markers: markers, representations: representations)
    }

    func write(_ clip: Clip) -> Int {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        for rep in clip.representations {
            item.setData(rep.data, forType: NSPasteboard.PasteboardType(rep.typeIdentifier))
        }
        pasteboard.writeObjects([item])
        return pasteboard.changeCount
    }
}
