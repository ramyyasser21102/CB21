import Foundation

/// Pasteboard marker types from the nspasteboard.org convention.
public enum PasteboardMarker {
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
}

/// What was on the system pasteboard at one change.
public struct PasteboardSnapshot: Sendable, Equatable {
    public let changeCount: Int
    public let markers: Set<String>
    public let representations: [Representation]

    public init(changeCount: Int, markers: Set<String>, representations: [Representation]) {
        self.changeCount = changeCount
        self.markers = markers
        self.representations = representations
    }
}

/// The system pasteboard, as far as cb21 needs it. The app target wraps `NSPasteboard`.
public protocol PasteboardReading: Sendable {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    /// Puts a Clip on the pasteboard and returns the resulting change count.
    func write(_ clip: Clip) -> Int
}

public enum SkipReason: Sendable, Equatable {
    case concealed
    case transient
    case ownWrite
}

public enum PollOutcome: Sendable, Equatable {
    case unchanged
    case skipped(SkipReason)
    /// The pasteboard changed but held nothing cb21 can store.
    case empty
    case captured(CaptureResult)
}

/// Turns pasteboard changes into History.
public actor CaptureEngine {
    private let pasteboard: any PasteboardReading
    private let store: ClipStore
    private var lastSeenChangeCount: Int
    private var ownWriteChangeCount: Int?

    /// Content already on the pasteboard at start is not captured.
    public init(pasteboard: any PasteboardReading, store: ClipStore) {
        self.pasteboard = pasteboard
        self.store = store
        self.lastSeenChangeCount = pasteboard.changeCount
    }

    public func poll(now: Date = Date()) async throws -> PollOutcome {
        let count = pasteboard.changeCount
        guard count != lastSeenChangeCount else { return .unchanged }
        lastSeenChangeCount = count

        if count == ownWriteChangeCount {
            ownWriteChangeCount = nil
            return .skipped(.ownWrite)
        }
        let snapshot = pasteboard.snapshot()
        if snapshot.markers.contains(PasteboardMarker.concealed) { return .skipped(.concealed) }
        if snapshot.markers.contains(PasteboardMarker.transient) { return .skipped(.transient) }
        guard !snapshot.representations.isEmpty else { return .empty }

        let clip = Clip(representations: snapshot.representations, createdAt: now)
        return .captured(try await store.capture(clip))
    }

    /// Puts a Clip back on the pasteboard and moves it to the top of History without capturing it again.
    public func recopy(id: UUID, now: Date = Date()) async throws {
        guard let clip = try await store.clip(id: id) else {
            throw StoreError(message: "no Clip with id \(id)")
        }
        ownWriteChangeCount = pasteboard.write(clip)
        try await store.recopy(id: id, at: now)
    }
}
